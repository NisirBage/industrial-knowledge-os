"""Industrial Reasoning Graph data model (M3 Component 4).

Distinct from both the Knowledge Graph (durable industrial facts) and the
Evidence Graph (per-query provenance chain): the Reasoning Graph represents
the *inferences* drawn from evidence — facts, causes, effects, risks,
hypotheses about contradictions, gaps, and eventually recommendations. It is
built structurally (see reasoning_graph_builder.py), never by asking an LLM
to "think step by step" — the summary exposed to users is generated by
walking this graph, not by exposing model chain-of-thought.
"""

from dataclasses import dataclass, field
from enum import Enum


class ReasoningNodeType(str, Enum):
    FACT = "fact"
    HYPOTHESIS = "hypothesis"
    CAUSE = "cause"
    EFFECT = "effect"
    RECOMMENDATION = "recommendation"
    RISK = "risk"
    UNKNOWN = "unknown"
    MISSING_EVIDENCE = "missing_evidence"


@dataclass(frozen=True)
class ReasoningNode:
    id: str
    node_type: ReasoningNodeType
    description: str
    confidence: float
    supporting_evidence_ids: list[str] = field(default_factory=list)


@dataclass(frozen=True)
class ReasoningEdge:
    source_id: str
    target_id: str
    relationship: str


@dataclass
class ReasoningGraph:
    nodes: list[ReasoningNode]
    edges: list[ReasoningEdge]
    summary: str

    def add_node(self, node: ReasoningNode) -> None:
        self.nodes.append(node)

    def add_edge(self, edge: ReasoningEdge) -> None:
        self.edges.append(edge)

    def nodes_of_type(self, node_type: ReasoningNodeType) -> list[ReasoningNode]:
        return [n for n in self.nodes if n.node_type == node_type]
